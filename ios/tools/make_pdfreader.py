#!/usr/bin/env python3
"""Builds BillBox/Resources/PDFReader/reader.js from the Mac app's own code (backend/src/services/pdfExtract.js), so the iPhone
joins PDF text into lines with exactly the Mac's functions. Run again whenever pdfExtract.js changes:  python3 tools/make_pdfreader.py"""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, '../backend/src/services/pdfExtract.js')).read()
start = src.index('/**\n * Watermarks')
end = src.index('/** Returns { pages: string[], text, method }')
mac = src[start:end].rstrip() + '\n'
out = '''// BillBox PDF reader for iPhone. GENERATED by ios/tools/make_pdfreader.py: do not edit by hand.
// The Mac reads supplier PDFs with pdf-parse 1.1.1, which runs Mozilla pdf.js 1.10.100 (no worker) and calls the
// pagerender function of backend/src/services/pdfExtract.js for each page. The iPhone runs the same pdf.js build (pdf.js,
// pdf.worker.js beside this file) and the code below, copied verbatim from pdfExtract.js, so each page reads exactly alike.
'use strict';

// ---- from backend/src/services/pdfExtract.js (Mac) ----
''' + mac + '''// ---- end of the Mac code ----

/** pdf-parse's loop: every page in order through pagerender; a page that fails is left out (the Mac's pagerender
 *  collects only the pages that succeed). Returns the page texts. */
async function readPdf(base64) {
  const bin = atob(base64);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  PDFJS.disableWorker = true;
  PDFJS.workerSrc = 'pdf.worker.js';
  const doc = await PDFJS.getDocument(bytes);
  const out = [];
  try {
    for (let i = 1; i <= doc.numPages; i++) {
      try {
        const pageData = await doc.getPage(i);
        out.push(await pageRender(pageData));
      } catch (e) { /* as pdf-parse: this page is skipped */ }
    }
  } finally {
    doc.destroy();
  }
  return out;
}
window.readPdf = readPdf;
'''
open(os.path.join(ROOT, 'BillBox/Resources/PDFReader/reader.js'), 'w').write(out)
print('reader.js written')
